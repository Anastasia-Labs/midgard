// The shared fixture for the affected-channels tests: a scratch directory
// removed after the run, the CLI runner, and a miniature Git repository with
// one golden channel.
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { after } from "node:test";
import assert from "node:assert/strict";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const script = join(here, "affected-channels.mjs");
export const realTable = join(here, "channels.json");
export const skillRoot = resolve(here, "..");
export const repositoryRoot = resolve(here, "../../../..");

export const scratch = mkdtempSync(join(tmpdir(), "affected-channels-test-"));
after(() => rmSync(scratch, { recursive: true, force: true }));

export const invoke = (args, cwd = scratch) => {
  // The ceiling keeps git from finding a repository above the scratch
  // directory, so "not a repository" stays true wherever tmpdir lives.
  const result = spawnSync(process.execPath, [script, ...args], {
    cwd,
    encoding: "utf8",
    env: { ...process.env, GIT_CEILING_DIRECTORIES: scratch },
  });
  return { code: result.status, out: result.stdout, err: result.stderr };
};

export const git = (root, ...args) => {
  const result = spawnSync(
    "git",
    [
      "-c",
      "user.name=fixture",
      "-c",
      "user.email=fixture@example.invalid",
      "-c",
      "commit.gpgsign=false",
      "-c",
      "core.hooksPath=/dev/null",
      ...args,
    ],
    { cwd: root, encoding: "utf8" },
  );
  assert.equal(result.status, 0, `git ${args.join(" ")}: ${result.stderr}`);
  return result.stdout;
};

export const write = (root, file, content) => {
  mkdirSync(dirname(join(root, file)), { recursive: true });
  writeFileSync(join(root, file), content);
};

