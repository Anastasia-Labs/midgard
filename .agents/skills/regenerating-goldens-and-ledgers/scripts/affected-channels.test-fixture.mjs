export const makeRepository = (
  name,
  { table = fixtureTable, init = true } = {},
) => {
  const root = join(scratch, name);
  write(
    root,
    "demo/pkg-a/package.json",
    JSON.stringify({
      name: "@x/a",
      scripts: {
        "fixtures:x:sync": "node scripts/generate-x.mjs",
        "fixtures:x:check": "node scripts/generate-x.mjs --check",
      },
    }),
  );
  write(root, "demo/pkg-a/src/index.ts", "export const x = 1;\n");
  write(
    root,
    "demo/pkg-a/scripts/generate-x.mjs",
    'const out = "onchain/aiken/lib/m/x-golden.test.ak";\n',
  );
  write(root, "demo/pkg-a/tests/fixtures/x.generated.json", "{}\n");
  write(
    root,
    "demo/pkg-b/package.json",
    JSON.stringify({
      name: "@x/b",
      dependencies: { "@x/a": "workspace:*" },
      scripts: { "docs:y:sync": "node scripts/sync-y.mjs" },
    }),
  );
  write(root, "demo/pkg-b/scripts/sync-y.mjs", "// writes docs/y.md\n");
  write(root, "demo/shared.mjs", "export {};\n");
  write(root, "docs/y.md", "# y\n");
  write(
    root,
    "onchain/aiken/lib/m/x-golden.test.ak",
    "// Generated by demo/pkg-a/scripts/generate-x.mjs\nuse m/helper\n",
  );
  write(root, "onchain/aiken/lib/m/helper.ak", "pub const h = 1\n");
  write(root, "onchain/aiken/lib/m/unrelated.ak", "pub const u = 1\n");
  write(root, "README.md", "# fixture\n");
  write(
    root,
    ".github/workflows/ci.yml",
    "name: CI\njobs:\n  a:\n    steps:\n      - name: Check x golden vectors\n        run: pnpm --dir demo/pkg-a run fixtures:x:check\n      - name: Other\n        run: echo\n",
  );
  write(root, "table.json", JSON.stringify(table, null, 2));
  if (init) {
    git(root, "init", "-q", "-b", "main");
    git(root, "add", "-A");
    git(root, "commit", "-q", "-m", "fixture");
  }
  return root;
};

