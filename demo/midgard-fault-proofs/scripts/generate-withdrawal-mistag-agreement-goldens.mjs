#!/usr/bin/env node

/**
 * Renders the withdrawal-mistag node-agreement vectors into the two Aiken test
 * modules that pin the chain's verdict on them.
 *
 * `tests/fixtures/withdrawal-mistag-agreement-vectors.json` is the one source:
 *
 *   * `valueRule`: a requested `l2_value` (raw CBOR, in the order admission
 *     accepted it), a ledger output's descriptor facts and the verdict of
 *     step-03's `output_value_matches_v1`;
 *   * `payability`: a withdrawal body (raw CBOR, as the order carries it), the
 *     withdrawn output's Cardano value size and the verdict of step-04's
 *     `payout_is_exactly_payable_v1` (`refused` is a body step-04 rejects
 *     outright, rendered as a `fail` test).
 *
 * The Aiken modules assert the chain reaches each pinned verdict. The
 * TypeScript twins (`tests/withdrawal-mistag.node-agreement.test.ts`,
 * `tests/withdrawal-mistag.payability-agreement.test.ts`) rebuild each case's
 * bytes, check they are the vector's, and check the node (and, for
 * payability, the SDK) reaches the same verdict. Edit the JSON, then
 * regenerate; never edit the modules by hand.
 *
 * usage: node scripts/generate-withdrawal-mistag-agreement-goldens.mjs [--check]
 */

import { readFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import {
  aikenBytes,
  formatAikenSource,
  goldenChannelEmitter,
  parseGoldenChannelArguments,
} from "@al-ft/midgard-core/scripts/golden-channel.mjs";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repositoryRoot = resolve(packageRoot, "../..");
const vectorsPath = join(
  packageRoot,
  "tests/fixtures/withdrawal-mistag-agreement-vectors.json",
);
const SYNC =
  "pnpm --dir demo/midgard-fault-proofs fixtures:withdrawal-mistag-agreement:sync";

const { checkOnly } = parseGoldenChannelArguments(
  "usage: node scripts/generate-withdrawal-mistag-agreement-goldens.mjs [--check]",
);
const writeOrCheck = goldenChannelEmitter({ repositoryRoot, checkOnly });

const { valueRule, payability } = JSON.parse(readFileSync(vectorsPath, "utf8"));

/** An Aiken integer literal with digit separators (`7_000_000`). */
const aikenInt = (value) => {
  if (!Number.isSafeInteger(value) || value < 0) {
    throw new Error(`expected a non-negative integer, got ${value}`);
  }
  return String(value).replace(/\B(?=(\d{3})+(?!\d))/gu, "_");
};

const caseName = (name) => {
  if (!/^[a-z][a-z0-9_]*$/u.test(name)) {
    throw new Error(`vector name ${name} is not an Aiken identifier`);
  }
  return `agrees_${name}`;
};

const unique = (vectors) => {
  const names = vectors.map(({ name }) => name);
  if (new Set(names).size !== names.length) {
    throw new Error("vector names must be unique");
  }
  return vectors;
};

const header = (lines) =>
  [
    "//// Generated by",
    "//// demo/midgard-fault-proofs/scripts/generate-withdrawal-mistag-agreement-goldens.mjs",
    `//// from demo/midgard-fault-proofs/tests/fixtures/withdrawal-mistag-agreement-vectors.json.`,
    `//// Do not edit; regenerate with \`${SYNC}\`.`,
    "////",
    ...lines.map((line) => (line === "" ? "////" : `//// ${line}`)),
  ].join("\n");

const valueRuleModule = () =>
  [
    header([
      "Node-agreement vectors for the withdrawal value rule.",
      "",
      "Each `agrees_<case>` test judges a requested `l2_value` (raw CBOR, in the",
      "order admission accepted it) against a ledger output's descriptor facts",
      "(lovelace, asset count, asset frontier commitment) with step-03's",
      "`output_value_matches_v1`, and pins the verdict. The TypeScript twin,",
      "demo/midgard-fault-proofs/tests/withdrawal-mistag.node-agreement.test.ts,",
      "rebuilds each case's output and value, checks these bytes and facts are",
      "that case's, and checks the node's `classifyWithdrawalFromLedger` reaches",
      "the same verdict.",
    ]),
    `
use aiken/cbor
use cardano/address
use cardano/assets
use cardano/transaction.{NoDatum, OutputReference}
use midgard/fraud_proofs/withdrawal_mistag/step_03
use midgard/ledger_state

fn chain_valid(
  l2_value_cbor: ByteArray,
  output_lovelace: Int,
  output_asset_count: Int,
  output_asset_frontier_commitment: ByteArray,
) -> Bool {
  expect Some(data) = cbor.deserialise(l2_value_cbor)
  expect l2_value: ledger_state.MidgardValue = data
  let body = ledger_state.WithdrawalBody {
    l2_outref: OutputReference { transaction_id: #"", output_index: 0 },
    l2_owner: #"",
    l2_value,
    l1_address: address.from_verification_key(#""),
    l1_datum: NoDatum,
  }
  step_03.output_value_matches_v1(
    body,
    assets.from_asset_list(l2_value),
    output_lovelace,
    output_asset_count,
    output_asset_frontier_commitment,
  )
}
`,
    ...unique(valueRule).map(
      (vector) => `test ${caseName(vector.name)}() {
  chain_valid(
    ${aikenBytes(vector.l2Value)},
    ${aikenInt(vector.outputLovelace)},
    ${aikenInt(vector.outputAssetCount)},
    ${aikenBytes(vector.outputAssetFrontierCommitment)},
  ) == ${vector.chainValid ? "True" : "False"}
}
`,
    ),
  ].join("\n");

const payabilityTest = (vector) => {
  const call = `  chain_payable(
    ${aikenBytes(vector.bodyCbor)},
    ${aikenInt(vector.cardanoValueSize)},
  )`;
  switch (vector.verdict) {
    case "payable":
    case "unpayable":
      return `test ${caseName(vector.name)}() {
${call} == ${vector.verdict === "payable" ? "True" : "False"}
}
`;
    case "refused":
      return `test ${caseName(vector.name)}() fail {
${call}
}
`;
    default:
      throw new Error(`${vector.name}: unknown verdict ${vector.verdict}`);
  }
};

const payabilityModule = () =>
  [
    header([
      "Node-agreement vectors for the withdrawal payability rule.",
      "",
      "Each `agrees_<case>` test judges a withdrawal body (raw CBOR, as the",
      "order carries it) and the withdrawn output's Cardano value size with",
      "step-04's `payout_is_exactly_payable_v1`, and pins the verdict; a `fail`",
      "case is a body step-04 refuses outright. The TypeScript twin,",
      "demo/midgard-fault-proofs/tests/withdrawal-mistag.payability-agreement.test.ts,",
      "rebuilds each case's body and output, checks these bytes and sizes are",
      "that case's, and checks that the SDK's `withdrawalMistagPayable` and the",
      "node's `classifyWithdrawalFromLedger` reach the same verdict.",
    ]),
    `
use aiken/cbor
use midgard/fraud_proofs/withdrawal_mistag/step_04
use midgard/ledger_state

fn chain_payable(body_cbor: ByteArray, cardano_value_size: Int) -> Bool {
  expect Some(data) = cbor.deserialise(body_cbor)
  expect body: ledger_state.WithdrawalBody = data
  step_04.payout_is_exactly_payable_v1(body, cardano_value_size)
}
`,
    ...unique(payability).map(payabilityTest),
  ].join("\n");

for (const [modulePath, source] of [
  [
    "onchain/aiken/lib/midgard/fraud-proofs/withdrawal-mistag/step-03.node-agreement.test.ak",
    valueRuleModule(),
  ],
  [
    "onchain/aiken/lib/midgard/fraud-proofs/withdrawal-mistag/step-04.node-agreement.test.ak",
    payabilityModule(),
  ],
]) {
  writeOrCheck(
    join(repositoryRoot, modulePath),
    formatAikenSource({
      source,
      fileName: basename(modulePath),
      repositoryRoot,
      tmpPrefix: "withdrawal-mistag-agreement-",
    }),
  );
}
