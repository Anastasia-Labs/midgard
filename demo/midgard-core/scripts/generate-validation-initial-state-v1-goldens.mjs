#!/usr/bin/env node

/**
 * The `validation-initial-state-v1` cross-language golden channel: state 0 of
 * a transaction's validation trace, which the on-chain claim derives
 * (`validation_claim_v1.derive_initial_state`) and the node derives through
 * `deriveMidgardValidationInitialStateV1`. A derivation mismatch would make
 * every honest trace start somewhere the claim does not, so both sides are
 * pinned to the same bytes:
 *
 *   * `tests/fixtures/validation-initial-state-v1.vectors.mjs` holds the
 *     structured inputs, driven through `dist/` here and through `src/` by the
 *     vitest suite;
 *   * `tests/fixtures/validation-initial-state-v1.generated.json` is the
 *     fixture that suite recomputes; and
 *   * `onchain/aiken/lib/midgard/validation-initial-state-v1-golden.test.ak`
 *     asserts the Aiken derivation, the context CBOR and the event-key
 *     serialisation on the same values.
 *
 * Vectors marked provisional carry script bytes and regenerate with any change
 * to how a script's identity is committed.
 *
 * usage: node scripts/generate-validation-initial-state-v1-goldens.mjs [--check]
 */

import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import {
  aikenBytes,
  formatAikenSource,
  goldenChannelEmitter,
  parseGoldenChannelArguments,
} from "./golden-channel.mjs";
import * as codec from "../dist/index.js";
import { deriveValidationInitialStateVectorsV1 } from "../tests/fixtures/validation-initial-state-v1.vectors.mjs";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(scriptDirectory, "..");
const repositoryRoot = resolve(packageRoot, "../..");
const generatedJsonPath = join(
  packageRoot,
  "tests/fixtures/validation-initial-state-v1.generated.json",
);
const aikenFileName = "validation-initial-state-v1-golden.test.ak";
const generatedAikenPath = join(
  repositoryRoot,
  "onchain/aiken/lib/midgard",
  aikenFileName,
);

const { checkOnly } = parseGoldenChannelArguments(
  "usage: node scripts/generate-validation-initial-state-v1-goldens.mjs [--check]",
);
const writeOrCheck = goldenChannelEmitter({ repositoryRoot, checkOnly });

const golden = deriveValidationInitialStateVectorsV1(codec);

const maxRedeemers = golden.transactions.find(
  ({ label }) => label === "max_redeemers_field",
);
if (
  maxRedeemers.redeemersPreimageBytes !==
  codec.MIDGARD_CONSENSUS_LIMITS.maxRedeemersPreimageBytes
) {
  throw new Error(
    "validation-initial-state-v1: max_redeemers_field no longer fills field 8",
  );
}

writeOrCheck(generatedJsonPath, `${JSON.stringify(golden, null, 2)}\n`);

// ## Aiken module

const headerFunctions = golden.headers
  .map(
    (header) => `
fn header_${header.label}() -> ledger_state.HeaderV1 {
  header_with(${header.endTimeMs}, ${header.blockSlot}, ${header.expectedNetworkId}, ${header.minFeeA}, ${header.minFeeB})
}

test context_of_header_${header.label}() {
  validation_claim_v1.derive_validation_context_cbor(header_${header.label}()) == ${aikenBytes(header.contextCbor)}
}`,
  )
  .join("\n");

const transactionConstants = golden.transactions
  .map(
    (transaction) => `
${transaction.provisional ? "// PROVISIONAL: carries script bytes.\n" : ""}const ${transaction.label}_tx_id = ${aikenBytes(transaction.transactionId)}

const ${transaction.label}_source =
  ledger_state.NativeTxProofSourceV1 {
    compact_cbor: ${aikenBytes(transaction.compactCbor)},
    witness_set_compact_cbor: ${aikenBytes(transaction.witnessSetCompactCbor)},
    field_preimage_lengths_cbor: ${aikenBytes(transaction.fieldPreimageLengthsCbor)},
  }`,
  )
  .join("\n");

const vectorTests = golden.vectors
  .map(
    (vector) => `
${vector.provisional ? "// PROVISIONAL: carries script bytes.\n" : ""}test ${vector.label}() {
  derives(
    header_${vector.header}(),
    ${vector.transaction}_tx_id,
    ${vector.transaction}_source,
    ${aikenBytes(vector.preUtxosRoot)},
    ${aikenBytes(vector.eventKeyCbor)},
    ${aikenBytes(vector.stateCbor)},
    ${aikenBytes(vector.stateHash)},
  )
}`,
  )
  .join("\n");

const aikenSource = `//// Generated by
//// demo/midgard-core/scripts/generate-validation-initial-state-v1-goldens.mjs.
//// Do not edit; regenerate. Every value comes from the TypeScript twin
//// \`deriveMidgardValidationInitialStateV1\`.
////
//// State 0 of a validation trace, derived from the header's context, the event
//// key, the source triple and the step's pre-state root. Vectors marked
//// PROVISIONAL carry script bytes and regenerate with any change to how a
//// script's identity is committed.

use aiken/cbor
use midgard/ledger_state
use midgard/transition_trace
use midgard/validation_claim_v1
use midgard/validation_trace_v1

fn header_with(
  end_time: Int,
  block_slot: Int,
  expected_network_id: Int,
  min_fee_a: Int,
  min_fee_b: Int,
) -> ledger_state.HeaderV1 {
  ledger_state.HeaderV1 {
    prev_utxos_root: #"",
    utxos_root: #"",
    withdrawals_root: #"",
    forced_transactions_root: #"",
    transactions_root: #"",
    deposits_root: #"",
    transition_trace_root: #"",
    event_to_step_root: #"",
    validation_traces_root: #"",
    withdrawal_count: 0,
    forced_transaction_count: 0,
    l2_transaction_count: 1,
    deposit_count: 0,
    total_event_count: 1,
    transition_step_count: 1,
    validation_trace_count: 1,
    start_time: 0,
    end_time,
    block_slot,
    expected_network_id,
    min_fee_a,
    min_fee_b,
    prev_header_hash: #"",
    operator_vkey: #"",
    protocol_version: 0,
  }
}

fn derives(
  header: ledger_state.HeaderV1,
  transaction_id: ByteArray,
  source: ledger_state.NativeTxProofSourceV1,
  pre_utxos_root: ByteArray,
  event_key_cbor: ByteArray,
  state_cbor: ByteArray,
  state_hash: ByteArray,
) -> Bool {
  let event_key = ledger_state.L2TransactionEventKey { tx_id: transaction_id }
  let membership =
    validation_claim_v1.NormalValidationSource {
      membership: transition_trace.RootMembershipProof {
        domain: transition_trace.TransactionsV1RootDomain,
        root: #"",
        phas_root: #"",
        count: 1,
        key: transaction_id,
        value: ledger_state.L2TransactionSourceV1 { tx_id: transaction_id, source },
        proof: [],
      },
    }
  let state =
    validation_claim_v1.derive_initial_state(
      header,
      event_key,
      membership,
      pre_utxos_root,
    )
  and {
    cbor.serialise(event_key) == event_key_cbor,
    validation_trace_v1.encode_machine_state(state) == state_cbor,
    validation_trace_v1.hash_machine_state(state) == state_hash,
  }
}
${headerFunctions}
${transactionConstants}
${vectorTests}
`;

writeOrCheck(
  generatedAikenPath,
  formatAikenSource({
    source: aikenSource,
    fileName: aikenFileName,
    repositoryRoot,
    tmpPrefix: "midgard-validation-initial-state-v1-aiken-format-",
  }),
);
