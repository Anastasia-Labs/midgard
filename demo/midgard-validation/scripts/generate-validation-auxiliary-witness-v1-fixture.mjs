import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

import { blake2b } from "@noble/hashes/blake2.js";
import { Constr, Data } from "@lucid-evolution/lucid";

import { encodeValidationAuxiliaryWitnessCborV1 } from "../dist/index.js";
import { canonicalValidationAuxiliaryWitnesses } from "../tests/fixtures/validation-auxiliary-witness-v1-canonical.ts";

const jsonPath = new URL(
  "../tests/fixtures/validation-auxiliary-witness-v1.generated.json",
  import.meta.url,
);
const aikenPath = new URL(
  "../../../onchain/aiken/lib/midgard/validation-auxiliary-witness-v1-abi-generated.ak",
  import.meta.url,
);
const checkOnly = process.argv.includes("--check");

const fail = (message) => {
  throw new Error(`validation auxiliary fixture generation failed: ${message}`);
};

if (canonicalValidationAuxiliaryWitnesses.length !== 40) {
  fail(
    `canonical input must contain exactly 40 constructors, got ${canonicalValidationAuxiliaryWitnesses.length}`,
  );
}

const constructors = canonicalValidationAuxiliaryWitnesses.map(
  ([tag, value], index) => {
    if (tag !== index) {
      fail(`canonical constructor ${index} declares tag ${tag}`);
    }
    const cbor = encodeValidationAuxiliaryWitnessCborV1(value).toString("hex");
    const decoded = Data.from(cbor);
    if (!(decoded instanceof Constr)) {
      fail(`constructor ${tag} did not encode as a Plutus constructor`);
    }
    if (decoded.index !== tag) {
      fail(`constructor ${tag} encoded as tag ${decoded.index}`);
    }
    return {
      tag,
      arity: decoded.fields.length,
      cbor,
      data: decoded,
    };
  },
);

const corpusCbor = Data.to(constructors.map(({ data }) => data));
const corpusBytes = Buffer.from(corpusCbor, "hex");
const corpusBlake2b256 = Buffer.from(
  blake2b(corpusBytes, { dkLen: 32 }),
).toString("hex");
const corpusSha256 = createHash("sha256").update(corpusBytes).digest("hex");
const arities = constructors.map(({ arity }) => arity);

const json = `${JSON.stringify(
  {
    schema: "midgard-validation-auxiliary-witness-v1",
    version: 1,
    constructors: constructors.map(({ tag, arity, cbor }) => ({
      tag,
      arity,
      cbor,
    })),
    corpusCbor,
    corpusBlake2b256,
    corpusSha256,
  },
  null,
  2,
)}\n`;

const cases = arities.map((arity, tag) => `    ${tag} -> ${arity}`).join("\n");
const arityLines = [];
let arityLine = "    ";
for (const arity of arities) {
  const next = `${arityLine === "    " ? "" : " "}${arity},`;
  if (arityLine.length + next.length > 81) {
    arityLines.push(arityLine);
    arityLine = `    ${arity},`;
  } else {
    arityLine += next;
  }
}
arityLines.push(arityLine);
const aiken = `// Generated by demo/midgard-validation/scripts/generate-validation-auxiliary-witness-v1-fixture.mjs.\n// Do not edit; update the typed canonical input and regenerate.\n\npub const auxiliary_corpus_cbor: ByteArray =\n  #"${corpusCbor}"\n\npub const auxiliary_corpus_blake2b_256: ByteArray =\n  #"${corpusBlake2b256}"\n\npub const auxiliary_arities: List<Int> =\n  [\n${arityLines.join("\n")}\n  ]\n\npub fn auxiliary_arity(tag: Int) -> Int {\n  when tag is {\n${cases}\n    _ -> -1\n  }\n}\n`;

const assertOrWrite = (path, expected) => {
  const filename = fileURLToPath(path);
  if (checkOnly) {
    let actual;
    try {
      actual = readFileSync(filename, "utf8");
    } catch (error) {
      fail(`missing generated artifact ${filename}: ${String(error)}`);
    }
    if (actual !== expected) {
      fail(`generated artifact is stale: ${filename}`);
    }
    return;
  }
  writeFileSync(filename, expected, "utf8");
};

assertOrWrite(jsonPath, json);
assertOrWrite(aikenPath, aiken);

if (!checkOnly) {
  process.stdout.write(
    `generated validation auxiliary fixture: 40 constructors, blake2b-256 ${corpusBlake2b256}\n`,
  );
}
