#!/usr/bin/env node

/**
 * Pins the bytes of the V1 CEK core-step evidence, `CoreStepEvidenceV1`, as
 * the TypeScript twin encodes it (`encodeMidgardCekCoreStepDataCbor`), against
 * the Aiken type it decodes into.
 *
 * Agreement between the two machines is the Aiken function evaluator's job:
 * `tests/cek-core-step.differential.test.ts` sends every step of the curated
 * programs of `tests/fixtures/cek-core-step-v1.vectors.mjs` to
 * `cek_machine_v1.verify_core_step_v1`. The evaluator passes a step's states
 * and witness as Data, so it never sees the evidence's bytes; this generator
 * pins them. Each pinned step's CBOR goes into
 * `onchain/aiken/lib/midgard/cek-core-step-v1-golden.test.ak`, which decodes
 * it into `cek_machine_v1.CoreStepEvidenceV1` and asserts that re-serialising
 * gives the same bytes.
 *
 * The plumbing — the `--check` contract, the `aiken fmt` trip, the emission —
 * is the shared `@al-ft/midgard-core/scripts/golden-channel.mjs`; only what is
 * computed lives here. `--check` asserts the checked-in module is exactly what
 * the twin produces today and never repairs it.
 *
 * usage: node scripts/generate-cek-core-step-v1-goldens.mjs [--check]
 */

import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { encodeCbor } from "@al-ft/midgard-core";
import {
  aikenBytes,
  formatAikenSource,
  goldenChannelEmitter,
  hex,
  parseGoldenChannelArguments,
} from "@al-ft/midgard-core/scripts/golden-channel.mjs";

import {
  buildMidgardCanonicalCekProgram,
  buildMidgardCekExecutionGraph,
  encodeMidgardCekCardanoFlatProgram,
  encodeMidgardCekCoreStepDataCbor,
  encodeMidgardCekPlutusData,
  executeMidgardCekStructuralProgram,
  verifyMidgardCekCoreStep,
} from "../dist/index.js";
import {
  CEK_CORE_STEP_PROGRAMS,
  compileMidgardCekGoldenProgram,
} from "../tests/fixtures/cek-core-step-v1.vectors.mjs";

const repositoryRoot = resolve(fileURLToPath(import.meta.url), "../../../..");
const aikenModule = "onchain/aiken/lib/midgard/cek-core-step-v1-golden.test.ak";

/**
 * The pinned steps. Between them they hold every CBOR form the encoder wrote
 * over all 855 steps of the curated programs on 2026-11-11: constructor tags
 * 121 to 127 and from 1280, definite and indefinite lists, integers and
 * lengths of one, two and four bytes, and a chunked byte string.
 */
const PINNED_STEPS = [
  {
    label: "map_round_trip_empty",
    index: 17,
    kind: "startBuiltinMapConversion",
  },
  {
    label: "schnorr_message_17_bytes",
    index: 18,
    kind: "executeBuiltinDirect",
  },
];

const { checkOnly } = parseGoldenChannelArguments(
  "usage: node scripts/generate-cek-core-step-v1-goldens.mjs [--check]",
);
const writeOrCheck = goldenChannelEmitter({ repositoryRoot, checkOnly });

const pinnedEvidence = ({ label, index, kind }) => {
  const definition = CEK_CORE_STEP_PROGRAMS.find(
    (candidate) => candidate.label === label,
  );
  if (definition === undefined) throw new Error(`no curated program ${label}`);
  const program = buildMidgardCanonicalCekProgram(
    encodeCbor(
      compileMidgardCekGoldenProgram(
        definition.term(),
        encodeMidgardCekCardanoFlatProgram,
      ),
    ),
  );
  const graph = buildMidgardCekExecutionGraph(
    program.termRoot,
    program.material.values(),
    encodeMidgardCekPlutusData(definition.context()),
  );
  const step = executeMidgardCekStructuralProgram({
    root: graph.root,
    material: graph.material.values(),
    constantWitnesses: graph.constantWitnesses,
    maxSteps: definition.maxSteps,
    executionBudget: definition.executionBudget,
  }).steps[index];
  if (step?.witness.kind !== kind)
    throw new Error(
      `${label} step ${index} is ${step?.witness.kind}, not ${kind}`,
    );
  if (!verifyMidgardCekCoreStep(step.pre, step.post, step.witness))
    throw new Error(`${label} step ${index} fails the TypeScript verifier`);
  return hex(encodeMidgardCekCoreStepDataCbor(step));
};

const renderAiken = () =>
  [
    "// Generated by demo/midgard-validation/scripts/generate-cek-core-step-v1-goldens.mjs.",
    "// Do not edit; regenerate from the TypeScript twin.",
    "//",
    "// The bytes of `CoreStepEvidenceV1` as the TypeScript twin",
    "// (`demo/midgard-validation/src/cek-data.ts`) encodes it: each one decodes",
    "// into the Aiken type and re-serialises to the same bytes. Whether the",
    "// machines agree on the steps is the Aiken function evaluator's test",
    "// (`demo/midgard-validation/tests/cek-core-step.differential.test.ts`).",
    "",
    "use aiken/cbor",
    "use midgard/cek_machine_v1.{CoreStepEvidenceV1}",
    "",
    "fn round_trips(evidence_cbor: ByteArray) -> Bool {",
    "  expect Some(data) = cbor.deserialise(evidence_cbor)",
    "  expect evidence: CoreStepEvidenceV1 = data",
    "  cbor.serialise(evidence) == evidence_cbor",
    "}",
    "",
    ...PINNED_STEPS.flatMap((pinned) => [
      `// ${pinned.label} step ${pinned.index}: ${pinned.kind}`,
      `test golden_${pinned.label}_s${String(pinned.index).padStart(2, "0")}_round_trips() {`,
      `  round_trips(${aikenBytes(pinnedEvidence(pinned))})`,
      "}",
      "",
    ]),
  ]
    .join("\n")
    .trimEnd()
    .concat("\n");

/**
 * The fork's `aiken fmt` leaves trailing spaces after monadic `let`/`expect`
 * lines; CI normalises them away over every tracked `.ak` file, so the
 * checked-in module must not carry them or `--check` and the format gate would
 * disagree about the same bytes.
 */
const stripTrailingWhitespace = (source) => source.replace(/[ \t]+$/gmu, "");

writeOrCheck(
  join(repositoryRoot, aikenModule),
  stripTrailingWhitespace(
    formatAikenSource({
      source: renderAiken(),
      fileName: "cek-core-step-v1-golden.test.ak",
      repositoryRoot,
      tmpPrefix: "midgard-cek-core-step-aiken-format-",
    }),
  ),
);
