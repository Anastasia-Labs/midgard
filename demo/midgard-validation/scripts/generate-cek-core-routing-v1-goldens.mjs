#!/usr/bin/env node

/**
 * Pins the CEK core routing of the TypeScript twins to the Aiken routing,
 * which stays the hand-written authority: the group `cekCoreGroup`
 * (`@al-ft/midgard-sdk`) gives a core step's mode and arm witness against
 * `cek_semantic_chain.core_group`, and the semantics group
 * `midgardCekSemanticGroup` gives a builtin tag against `semantic_group`.
 *
 * The rows are `tests/fixtures/cek-core-routing-v1.vectors.mjs`'s over the
 * built twins. It writes:
 *
 *   * `tests/fixtures/cek-core-routing-v1.generated.json`, which
 *     `tests/cek-core-routing-v1.golden.test.ts` checks the twins against;
 *   * `onchain/aiken/validators/fraud-proofs/validation-trace/cek-core-routing-golden.test.ak`,
 *     in which each routed row must route to the same group and each refused
 *     row must fail.
 *
 * The plumbing — the `--check` contract, the `aiken fmt` trip, the emission —
 * is the shared `@al-ft/midgard-core/scripts/golden-channel.mjs`. `--check`
 * asserts the checked-in artifacts are exactly what the twins give today and
 * never repairs them.
 *
 * usage: node scripts/generate-cek-core-routing-v1-goldens.mjs [--check]
 */

import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import {
  formatAikenSource,
  goldenChannelEmitter,
  parseGoldenChannelArguments,
} from "@al-ft/midgard-core/scripts/golden-channel.mjs";
import { cekCoreGroup } from "@al-ft/midgard-sdk";

import { midgardCekSemanticGroup } from "../dist/index.js";
import { routingRows } from "../tests/fixtures/cek-core-routing-v1.vectors.mjs";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repositoryRoot = resolve(packageRoot, "../..");
const generatedJsonPath = join(
  packageRoot,
  "tests/fixtures/cek-core-routing-v1.generated.json",
);
const aikenFileName = "cek-core-routing-golden.test.ak";
const generatedAikenPath = join(
  repositoryRoot,
  "onchain/aiken/validators/fraud-proofs/validation-trace",
  aikenFileName,
);

const { checkOnly } = parseGoldenChannelArguments(
  "usage: node scripts/generate-cek-core-routing-v1-goldens.mjs [--check]",
);
const writeOrCheck = goldenChannelEmitter({ repositoryRoot, checkOnly });

const rows = routingRows({
  coreGroup: cekCoreGroup,
  semanticGroup: midgardCekSemanticGroup,
});

const PREAMBLE = `//// Generated by demo/midgard-validation/scripts/generate-cek-core-routing-v1-goldens.mjs.
//// Do not edit; regenerate with
//// \`pnpm --dir demo/midgard-validation run fixtures:cek-core-routing-v1:sync\`.
////
//// The CEK core routing of the TypeScript twins (\`cekCoreGroup\` in
//// midgard-sdk, \`midgardCekSemanticGroup\` in midgard-validation): each
//// routed row must route to the twin's group here, and each refused row must
//// fail.

use aiken/builtin
use aiken/collection/list
use midgard/cek_semantic_chain as chain

/// A witness of constructor \`arm\`; the builtin arms 30 and 38 carry \`tag\`
/// where \`core_group\` reads it.
fn witness(arm: Int, tag: Int) -> Data {
  if arm == 30 {
    builtin.constr_data(30, [builtin.i_data(tag), builtin.i_data(0), builtin.i_data(0)])
  } else if arm == 38 {
    builtin.constr_data(38, [builtin.i_data(tag), builtin.i_data(0)])
  } else {
    builtin.constr_data(arm, [])
  }
}

fn routes_core(rows: List<(Int, Int, Int, Int)>) -> Bool {
  list.all(
    rows,
    fn(row) {
      let (mode, arm, tag, group) = row
      chain.core_group(mode, witness(arm, tag)) == group
    },
  )
}
`;

const tuple = (values) => `(${values.join(", ")})`;

const name = (value) => (value < 0 ? `minus_${-value}` : String(value));

const renderAiken = () => {
  const modes = [...new Set(rows.coreGroup.routed.map(({ mode }) => mode))];
  return [
    PREAMBLE,
    ...modes.map((mode) =>
      [
        `test core_group_routes_mode_${mode}() {`,
        `  routes_core([${rows.coreGroup.routed
          .filter((row) => row.mode === mode)
          .map(({ arm, tag, group }) => tuple([mode, arm, tag, group]))
          .join(", ")}])`,
        "}",
        "",
      ].join("\n"),
    ),
    ...rows.coreGroup.refused.map(({ mode, arm, tag }) =>
      [
        `test core_group_refuses_mode_${mode}_arm_${arm}${tag === 0 ? "" : `_tag_${tag}`}() fail {`,
        `  chain.core_group(${mode}, witness(${arm}, ${tag})) >= 0`,
        "}",
        "",
      ].join("\n"),
    ),
    [
      "test semantic_group_routes() {",
      "  list.all(",
      `    [${rows.semanticGroup.routed
        .map(({ tag, group }) => tuple([tag, group]))
        .join(", ")}],`,
      "    fn(row) {",
      "      let (tag, group) = row",
      "      chain.semantic_group(tag) == group",
      "    },",
      "  )",
      "}",
      "",
    ].join("\n"),
    ...rows.semanticGroup.refused.map(({ tag }) =>
      [
        `test semantic_group_refuses_tag_${name(tag)}() fail {`,
        `  chain.semantic_group(${tag}) >= 0`,
        "}",
        "",
      ].join("\n"),
    ),
  ].join("\n");
};

/**
 * The fork's `aiken fmt` leaves trailing spaces after monadic `let`/`expect`
 * lines; CI normalises them away over every tracked `.ak` file, so the
 * checked-in module must not carry them.
 */
const stripTrailingWhitespace = (source) => source.replace(/[ \t]+$/gmu, "");

writeOrCheck(
  generatedJsonPath,
  `${JSON.stringify(
    {
      generator:
        "demo/midgard-validation/scripts/generate-cek-core-routing-v1-goldens.mjs",
      ...rows,
    },
    null,
    2,
  )}\n`,
);
writeOrCheck(
  generatedAikenPath,
  stripTrailingWhitespace(
    formatAikenSource({
      source: renderAiken(),
      fileName: aikenFileName,
      repositoryRoot,
      tmpPrefix: "cek-core-routing-v1-",
    }),
  ),
);
