#!/usr/bin/env node

/**
 * Emits the known builtin failure conformance vectors: a JSON fixture and the
 * Aiken module
 * `onchain/aiken/lib/midgard/known-builtin-failure-conformance-golden.test.ak`.
 *
 * Each row is a case of `tests/fixtures/known-builtin-failure-conformance.cases.mjs`
 * and the verdict the off-chain twin `midgardCekKnownBuiltinFailure` (run
 * here from the built `dist/`) gives it: `known`, `not-known` or `refused`.
 * The off-chain twin must match the on-chain rule, so the Aiken module holds
 * `cek_builtin_v1.known_builtin_failure_v1` to every verdict: one test per
 * tag holds the known and not-known cases, and each refused case is a test
 * that must fail. `tests/known-builtin-failure-conformance.golden.test.ts`
 * runs the twin from `src/` over the same cases and compares with the
 * checked-in fixture.
 *
 * usage: node scripts/generate-known-builtin-failure-conformance-goldens.mjs [--check]
 * (run `pnpm run build` first; it reads `dist`).
 */

import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import {
  aikenBytes,
  formatAikenSource,
  goldenChannelEmitter,
  parseGoldenChannelArguments,
} from "@al-ft/midgard-core/scripts/golden-channel.mjs";

import { midgardCekKnownBuiltinFailure } from "../dist/cek-builtin.js";
import { buildKnownBuiltinFailureConformanceRows } from "../tests/fixtures/known-builtin-failure-conformance.cases.mjs";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(scriptDirectory, "..");
const repositoryRoot = resolve(packageRoot, "../..");
const generatedJsonPath = join(
  packageRoot,
  "tests/fixtures/known-builtin-failure-conformance.generated.json",
);
const generatedAikenPath = join(
  repositoryRoot,
  "onchain/aiken/lib/midgard/known-builtin-failure-conformance-golden.test.ak",
);

const { checkOnly } = parseGoldenChannelArguments(
  "usage: node scripts/generate-known-builtin-failure-conformance-goldens.mjs [--check]",
);
const writeOrCheck = goldenChannelEmitter({ repositoryRoot, checkOnly });

const rows = buildKnownBuiltinFailureConformanceRows(
  midgardCekKnownBuiltinFailure,
);

const argumentText = (argument) => {
  switch (argument.kind) {
    case "constant":
      return `constant(${aikenBytes(argument.type)}, ${aikenBytes(argument.payload)})`;
    case "semanticConstant":
      return `semantic(${aikenBytes(argument.type)}, ${aikenBytes(argument.root)}, ${argument.cborLength}, ${argument.payloadMemory}, ${argument.memory})`;
    case "opaque":
      return `OpaqueValue(${aikenBytes(argument.root)})`;
    case "blsMillerLoop":
      return `BlsMillerLoopValue(${aikenBytes(argument.root)})`;
    default:
      throw new Error(`no Aiken form for a ${String(argument.kind)} argument`);
  }
};

const argumentsText = (row) =>
  `[${row.arguments.map(argumentText).join(", ")}]`;

const tagLabel = (tag) =>
  tag < 0 ? `minus_${String(-tag)}` : String(tag).padStart(3, "0");

const caseLabel = (row) => String(row.case).padStart(4, "0");

const verdictsTest = (title, decided) => [
  `test ${title}() {`,
  "  verdicts_hold(",
  "    [",
  ...decided.map(
    (row) =>
      `      Case { id: ${row.case}, tag: ${row.tag}, arguments: ${argumentsText(row)}, known: ${row.verdict === "known" ? "True" : "False"} },`,
  ),
  "    ],",
  "  )",
  "}",
  "",
];

const refusedTest = (row) => [
  `// ${row.name}`,
  `test tag_${tagLabel(row.tag)}_case_${caseLabel(row)}_refused() fail {`,
  `  known_builtin_failure_v1(${row.tag}, ${argumentsText(row)}) || True`,
  "}",
  "",
];

const renderAiken = () => {
  const lines = [
    "//// Generated by",
    "//// demo/midgard-validation/scripts/generate-known-builtin-failure-conformance-goldens.mjs",
    "//// from demo/midgard-validation/tests/fixtures/known-builtin-failure-conformance.cases.mjs.",
    "//// Do not edit; run `pnpm --dir demo/midgard-validation run",
    "//// fixtures:known-builtin-failure-conformance:sync`.",
    "////",
    "//// Each case is a builtin application and the verdict the off-chain twin",
    "//// `midgardCekKnownBuiltinFailure` gives it; the off-chain twin must match",
    "//// the on-chain rule. `known_builtin_failure_v1` is held to every verdict:",
    "//// a `verdicts` test per tag holds its known and not-known cases (by case",
    "//// number, as in the JSON fixture), and each refused case is a test that",
    "//// must fail.",
    "",
    "use aiken/collection/list",
    "use midgard/cek_builtin_v1.{",
    "  BlsMillerLoopValue, OpaqueValue, ValueWitnessV1, known_builtin_failure_v1,",
    "}",
    "use midgard/cek_constant_v1",
    "use midgard/cek_data_v1",
    "",
    "type Case {",
    "  id: Int,",
    "  tag: Int,",
    "  arguments: List<ValueWitnessV1>,",
    "  known: Bool,",
    "}",
    "",
    "fn constant(type_cbor: ByteArray, payload_cbor: ByteArray) -> ValueWitnessV1 {",
    "  cek_builtin_v1.ConstantValue(",
    "    cek_constant_v1.ConstantWitnessV1 { type_cbor, payload_cbor },",
    "  )",
    "}",
    "",
    "fn semantic(",
    "  type_cbor: ByteArray,",
    "  root: ByteArray,",
    "  cbor_length: Int,",
    "  payload_memory: Int,",
    "  memory: Int,",
    ") -> ValueWitnessV1 {",
    "  cek_builtin_v1.SemanticConstantValue {",
    "    type_cbor,",
    "    payload: cek_data_v1.DataSummaryV1 {",
    "      root,",
    "      cbor_length,",
    "      memory: payload_memory,",
    "    },",
    "    memory,",
    "  }",
    "}",
    "",
    "fn verdicts_hold(cases: List<Case>) -> Bool {",
    "  list.all(",
    "    cases,",
    "    fn(entry) {",
    "      if known_builtin_failure_v1(entry.tag, entry.arguments) == entry.known {",
    "        True",
    "      } else {",
    '        trace @"verdict differs on case": entry.id',
    "        False",
    "      }",
    "    },",
    "  )",
    "}",
    "",
  ];

  const tags = [...new Set(rows.map((row) => row.tag))].sort((a, b) => a - b);
  const outside = [];
  for (const tag of tags) {
    const ofTag = rows.filter((row) => row.tag === tag);
    const decided = ofTag.filter((row) => row.verdict !== "refused");
    if (!ofTag.some((row) => row.verdict === "known")) {
      outside.push(...ofTag);
      continue;
    }
    lines.push(...verdictsTest(`tag_${tagLabel(tag)}_verdicts`, decided));
    for (const row of ofTag) {
      if (row.verdict === "refused") lines.push(...refusedTest(row));
    }
  }
  if (outside.some((row) => row.verdict !== "not-known")) {
    throw new Error("a tag with no known case has a refused case");
  }
  lines.push(...verdictsTest("tags_without_known_failures_verdicts", outside));
  return `${lines.join("\n")}\n`;
};

writeOrCheck(generatedJsonPath, `${JSON.stringify({ rows }, null, 2)}\n`);
writeOrCheck(
  generatedAikenPath,
  formatAikenSource({
    source: renderAiken(),
    fileName: "known-builtin-failure-conformance-golden.test.ak",
    repositoryRoot,
    tmpPrefix: "known-builtin-failure-conformance-aiken-",
  }),
);
