#!/usr/bin/env node

/**
 * Renders the pinned builtin-step evidence into the two Aiken modules the
 * on-chain step tests import.
 *
 * `tests/fixtures/cek-builtin-step-evidence-vectors.json` is the one source.
 * Each vector is a label and the hex of one `CoreStepEvidenceV1` (a CEK core
 * step: pre-state, post-state and witness, as Data CBOR):
 *
 *   * `directListConstruct`: mkCons steps, one per element type, with the
 *     witness the executor emits and, for the direct rows, the compacted
 *     semantic witness of the same step;
 *   * `semanticPresentation`: semantic builtin steps over Data, list and pair
 *     values, presented by summary.
 *
 * The Aiken test modules (`cek-direct-list-construct.test.ak`,
 * `cek-semantic-presentation.test.ak`) prove each step and refuse its
 * mutations. The TypeScript twins
 * (`tests/cek-executor.direct-list-construct.test.ts`,
 * `tests/cek-executor.semantic-presentation.test.ts`) check that the executor
 * emits exactly these bytes. Edit the JSON, then regenerate; never edit the
 * generated modules by hand.
 *
 * usage: node scripts/generate-cek-builtin-step-evidence-goldens.mjs [--check]
 */

import { readFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import {
  aikenBytes,
  formatAikenSource,
  goldenChannelEmitter,
  parseGoldenChannelArguments,
} from "@al-ft/midgard-core/scripts/golden-channel.mjs";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repositoryRoot = resolve(packageRoot, "../..");
const vectorsPath = join(
  packageRoot,
  "tests/fixtures/cek-builtin-step-evidence-vectors.json",
);
const SYNC =
  "pnpm --dir demo/midgard-validation fixtures:cek-builtin-step-evidence:sync";

const { checkOnly } = parseGoldenChannelArguments(
  "usage: node scripts/generate-cek-builtin-step-evidence-goldens.mjs [--check]",
);
const writeOrCheck = goldenChannelEmitter({ repositoryRoot, checkOnly });

const { directListConstruct, semanticPresentation } = JSON.parse(
  readFileSync(vectorsPath, "utf8"),
);

const constantName = (name) => {
  if (!/^[a-z][a-z0-9_]*$/u.test(name)) {
    throw new Error(`vector name ${name} is not an Aiken identifier`);
  }
  return `${name}_evidence`;
};

const evidenceHex = (name, evidence) => {
  if (
    typeof evidence !== "string" ||
    evidence.length === 0 ||
    !/^(?:[0-9a-f]{2})+$/u.test(evidence)
  ) {
    throw new Error(`vector ${name} evidence is not lowercase hex bytes`);
  }
  return evidence;
};

const unique = (vectors) => {
  const names = vectors.map(({ name }) => name);
  if (new Set(names).size !== names.length) {
    throw new Error("vector names must be unique");
  }
  return vectors;
};

const header = (lines) =>
  [
    "//// Generated by",
    "//// demo/midgard-validation/scripts/generate-cek-builtin-step-evidence-goldens.mjs",
    "//// from demo/midgard-validation/tests/fixtures/cek-builtin-step-evidence-vectors.json.",
    `//// Do not edit; regenerate with \`${SYNC}\`.`,
    "////",
    ...lines.map((line) => (line === "" ? "////" : `//// ${line}`)),
  ].join("\n");

const evidenceModule = (lines, vectors) =>
  [
    header(lines),
    ...unique(vectors).map(
      ({ name, evidence }) =>
        `pub const ${constantName(name)}: ByteArray =\n  ${aikenBytes(evidenceHex(name, evidence))}`,
    ),
  ].join("\n\n") + "\n";

const modules = [
  {
    target:
      "onchain/aiken/lib/midgard/cek-direct-list-construct-evidence-generated.ak",
    source: evidenceModule(
      [
        "Pinned mkCons step evidence, one `CoreStepEvidenceV1` per constant.",
        "",
        "cek-direct-list-construct.test.ak proves each step and refuses its",
        "mutations. The TypeScript twin,",
        "demo/midgard-validation/tests/cek-executor.direct-list-construct.test.ts,",
        "checks the executor emits exactly these bytes.",
      ],
      directListConstruct,
    ),
  },
  {
    target:
      "onchain/aiken/lib/midgard/cek-semantic-presentation-evidence-generated.ak",
    source: evidenceModule(
      [
        "Pinned semantic builtin step evidence, one `CoreStepEvidenceV1` per",
        "constant.",
        "",
        "cek-semantic-presentation.test.ak proves each step and refuses each",
        "presented value moved by one word. The TypeScript twin,",
        "demo/midgard-validation/tests/cek-executor.semantic-presentation.test.ts,",
        "checks the executor emits exactly these bytes.",
      ],
      semanticPresentation,
    ),
  },
];

for (const { target, source } of modules) {
  const path = join(repositoryRoot, target);
  writeOrCheck(
    path,
    formatAikenSource({
      source,
      fileName: basename(path),
      repositoryRoot,
      tmpPrefix: "cek-builtin-step-evidence-",
    }),
  );
}
