#!/usr/bin/env node

/**
 * Emits the script-decode step golden vectors: a JSON fixture and the Aiken
 * module `onchain/aiken/lib/midgard/script-decode-v1-golden.test.ak`.
 *
 * Each row is a script walked by the TypeScript port of the step machine
 * (`planScriptDecodeWalk`), Walk by Walk: how many frames each Walk reveals,
 * and the hash of every run datum and of the record. The Aiken module replays
 * every walk with `midgard/script_decode_v1.step_with_frames_v1` and checks
 * each hash. The rows are built by
 * `tests/fixtures/script-decode-step-v1.vectors.mjs` through the built `dist/`
 * here, and through `src/` by `tests/script-decode-step-v1.golden.test.ts`,
 * which compares them with the checked-in fixture.
 *
 * usage: node scripts/generate-script-decode-step-v1-goldens.mjs [--check]
 */

import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { midgardBlake2b } from "@al-ft/midgard-core";
import {
  aikenBytes,
  formatAikenSource,
  goldenChannelEmitter,
  parseGoldenChannelArguments,
} from "@al-ft/midgard-core/scripts/golden-channel.mjs";

import {
  planScriptDecodeWalk,
  scriptDecodeRecordData,
  scriptDecodeRunData,
  serialiseScriptDecodeData,
} from "../dist/index.js";
import { buildScriptDecodeStepRows } from "../tests/fixtures/script-decode-step-v1.vectors.mjs";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(scriptDirectory, "..");
const repositoryRoot = resolve(packageRoot, "../..");
const generatedJsonPath = join(
  packageRoot,
  "tests/fixtures/script-decode-step-v1.generated.json",
);
const generatedAikenPath = join(
  repositoryRoot,
  "onchain/aiken/lib/midgard/script-decode-v1-golden.test.ak",
);

const { checkOnly } = parseGoldenChannelArguments(
  "usage: node scripts/generate-script-decode-step-v1-goldens.mjs [--check]",
);
const writeOrCheck = goldenChannelEmitter({ repositoryRoot, checkOnly });

const rows = buildScriptDecodeStepRows({
  planWalk: planScriptDecodeWalk,
  runData: scriptDecodeRunData,
  recordData: scriptDecodeRecordData,
  serialise: serialiseScriptDecodeData,
  blake2b256: (bytes) => midgardBlake2b(bytes, { dkLen: 32 }),
});

const pad2 = (index) => String(index).padStart(2, "0");

const slug = (label) =>
  label
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_|_$/g, "");

const renderAiken = () => {
  const lines = [
    "//// Generated by",
    "//// demo/midgard-validation/scripts/generate-script-decode-step-v1-goldens.mjs",
    "//// from tests/fixtures/script-decode-step-v1.vectors.mjs. Do not edit;",
    "//// run `pnpm --dir demo/midgard-validation run",
    "//// fixtures:script-decode-step-v1:sync`.",
    "////",
    "//// Each row is a script walked by the TypeScript port of the step machine:",
    "//// how many frames each Walk reveals and the hash of the run datum it",
    "//// writes, then the hash of the record. `step_with_frames_v1` replays every",
    "//// walk and must write the same datums.",
    "",
    "use aiken/builtin",
    "use aiken/cbor",
    "use aiken/crypto.{blake2b_224, blake2b_256}",
    "use midgard/script_decode_v1.{",
    "  DecodeEnv, Frame, ScriptDecodeRunV1, decode_env_v1, initial_run_v1, is_terminal,",
    "  record_of_v1, step_with_frames_v1,",
    "}",
    "",
    "fn run_hash(run: ScriptDecodeRunV1) -> ByteArray {",
    "  blake2b_256(cbor.serialise(run))",
    "}",
    "",
    "fn walk(",
    "  env: DecodeEnv,",
    "  run: ScriptDecodeRunV1,",
    "  frames: List<Frame>,",
    "  fuel: Int,",
    "  steps: List<(Int, ByteArray)>,",
    ") -> ScriptDecodeRunV1 {",
    "  when steps is {",
    "    [] -> {",
    "      expect is_terminal(run.machine.control)",
    "      run",
    "    }",
    "    [(visible, expected), ..rest] -> {",
    "      expect !is_terminal(run.machine.control)",
    "      let (machine, after) =",
    "        step_with_frames_v1(env, run.machine, frames, visible, fuel)",
    "      let next = ScriptDecodeRunV1 { ..run, machine }",
    "      expect run_hash(next) == expected",
    "      walk(env, next, after, fuel, rest)",
    "    }",
    "  }",
    "}",
    "",
    "fn walks(",
    "  language: Int,",
    "  script: ByteArray,",
    "  fuel: Int,",
    "  script_hash: ByteArray,",
    "  initial_run_hash: ByteArray,",
    "  steps: List<(Int, ByteArray)>,",
    "  record_hash: ByteArray,",
    ") -> Bool {",
    "  expect blake2b_224(builtin.cons_bytearray(language, script)) == script_hash",
    "  let run = initial_run_v1(script_hash, language, script)",
    "  expect run_hash(run) == initial_run_hash",
    "  let last = walk(decode_env_v1(script, run), run, [], fuel, steps)",
    "  expect Some(record) = record_of_v1(last)",
    "  blake2b_256(cbor.serialise(record)) == record_hash",
    "}",
    "",
  ];

  rows.forEach((row, index) => {
    lines.push(`/// ${row.label}`);
    lines.push(`test row_${pad2(index)}_${slug(row.label)}() {`);
    lines.push("  walks(");
    lines.push(`    ${row.language},`);
    lines.push(`    ${aikenBytes(row.script)},`);
    lines.push(`    ${row.fuel},`);
    lines.push(`    ${aikenBytes(row.scriptHash)},`);
    lines.push(`    ${aikenBytes(row.initialRunHash)},`);
    lines.push("    [");
    for (const step of row.steps) {
      lines.push(`      (${step.visible}, ${aikenBytes(step.runHash)}),`);
    }
    lines.push("    ],");
    lines.push(`    ${aikenBytes(row.recordHash)},`);
    lines.push("  )");
    lines.push("}");
    lines.push("");
  });
  return `${lines.join("\n")}\n`;
};

writeOrCheck(generatedJsonPath, `${JSON.stringify({ rows }, null, 2)}\n`);
writeOrCheck(
  generatedAikenPath,
  formatAikenSource({
    source: renderAiken(),
    fileName: "script-decode-v1-golden.test.ak",
    repositoryRoot,
    tmpPrefix: "midgard-script-decode-step-aiken-format-",
  }),
);
