#!/usr/bin/env node

/**
 * Emits the Plutus Data CBOR decoding golden vectors: a JSON fixture and the
 * Aiken module `onchain/aiken/lib/midgard/cbor-deserialise-v1-golden.test.ak`.
 *
 * Each row is an input and what the TypeScript decoder's two entries return
 * for it (`plutusDataFromCborIterative`, the Data entry, and
 * `midgardEnvelopeDataFromCborIterative`, the envelope entry), written as the
 * canonical serialisation of the decoded value, or `null` where the entry
 * refuses. The Aiken module holds `midgard/cbor_deserialise`'s entries of the
 * same names to every row, in both variants. The rows are built by
 * `tests/fixtures/plutus-data-cbor-decoding-v1.vectors.mjs` through the built
 * `dist/` here, and through `src/` by
 * `tests/plutus-data-cbor-decoding-v1.golden.test.ts`, which compares them
 * with the checked-in fixture.
 *
 * usage: node scripts/generate-plutus-data-cbor-decoding-v1-goldens.mjs [--check]
 */

import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { encodeCborBytes } from "@al-ft/midgard-core/codec/cbor";
import { compactPlutusDataCarriageCbor } from "@al-ft/midgard-core/plutus-data-cbor";
import {
  aikenBytes,
  formatAikenSource,
  goldenChannelEmitter,
  parseGoldenChannelArguments,
} from "@al-ft/midgard-core/scripts/golden-channel.mjs";

import {
  encodeMidgardCekPlutusData,
  midgardEnvelopeDataFromCborIterative,
  plutusDataFromCborIterative,
} from "../dist/index.js";
import { buildPlutusDataCborDecodingRows } from "../tests/fixtures/plutus-data-cbor-decoding-v1.vectors.mjs";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(scriptDirectory, "..");
const repositoryRoot = resolve(packageRoot, "../..");
const generatedJsonPath = join(
  packageRoot,
  "tests/fixtures/plutus-data-cbor-decoding-v1.generated.json",
);
const generatedAikenPath = join(
  repositoryRoot,
  "onchain/aiken/lib/midgard/cbor-deserialise-v1-golden.test.ak",
);

const { checkOnly } = parseGoldenChannelArguments(
  "usage: node scripts/generate-plutus-data-cbor-decoding-v1-goldens.mjs [--check]",
);
const writeOrCheck = goldenChannelEmitter({ repositoryRoot, checkOnly });

/** Rows per generated Aiken test, so no one test carries every row. */
const AIKEN_ROWS_PER_TEST = 40;

const rows = buildPlutusDataCborDecodingRows({
  decodeData: plutusDataFromCborIterative,
  decodeEnvelope: midgardEnvelopeDataFromCborIterative,
  encodeData: encodeMidgardCekPlutusData,
  encodeCborBytes,
  compactCarriageCbor: compactPlutusDataCarriageCbor,
});

const pad3 = (index) => String(index).padStart(3, "0");

// The Aiken side spells a refusal `#""`: no value serialises to no bytes.
const expected = (outcome) => aikenBytes(outcome ?? "");

const renderAiken = () => {
  const lines = [
    "//// Generated by",
    "//// demo/midgard-validation/scripts/generate-plutus-data-cbor-decoding-v1-goldens.mjs",
    "//// from tests/fixtures/plutus-data-cbor-decoding-v1.vectors.mjs. Do not edit;",
    "//// run `pnpm --dir demo/midgard-validation run",
    "//// fixtures:plutus-data-cbor-decoding-v1:sync`.",
    "////",
    "//// Each row is an input and what the TypeScript decoder's Data entry and",
    "//// envelope entry return for it: the canonical serialisation of the decoded",
    '//// value, or `#""` where the entry refuses. Both entries of',
    "//// `midgard/cbor_deserialise` are held to every row, in both variants.",
    "",
    "use aiken/cbor",
    "use aiken/collection/list",
    "use aiken/fuzz",
    "use midgard/cbor_deserialise",
    "",
    "type Row {",
    "  input: ByteArray,",
    "  data: ByteArray,",
    "  envelope: ByteArray,",
    "}",
    "",
    "fn returns(decoded: Option<Data>, expected: ByteArray) -> Bool {",
    "  when decoded is {",
    '    None -> expected == #""',
    "    Some(data) -> cbor.serialise(data) == expected",
    "  }",
    "}",
    "",
    "fn rows_agree(rows: List<Row>) -> Bool {",
    "  list.all(",
    "    rows,",
    "    fn(row) {",
    "      and {",
    "        returns(cbor_deserialise.deserialise(row.input), row.data),",
    "        returns(cbor_deserialise.deserialise_envelope(row.input), row.envelope),",
    '        row.data == #"" || cbor_deserialise.expect_deserialise(',
    "          row.input,",
    "          fn(data) { cbor.serialise(data) == row.data },",
    "        ),",
    '        row.envelope == #"" || cbor_deserialise.expect_deserialise_envelope(',
    "          row.input,",
    "          fn(data) { cbor.serialise(data) == row.envelope },",
    "        ),",
    "      }",
    "    },",
    "  )",
    "}",
    "",
  ];

  for (let from = 0; from < rows.length; from += AIKEN_ROWS_PER_TEST) {
    const chunk = rows.slice(from, from + AIKEN_ROWS_PER_TEST);
    const to = from + chunk.length - 1;
    lines.push(`test rows_${pad3(from)}_${pad3(to)}_agree() {`);
    lines.push("  rows_agree(");
    lines.push("    [");
    for (const row of chunk) {
      lines.push(
        `      Row { input: ${aikenBytes(row.input)}, data: ${expected(row.data)}, envelope: ${expected(row.envelope)} },`,
      );
    }
    lines.push("    ],");
    lines.push("  )");
    lines.push("}");
    lines.push("");
  }

  // The failing variants on every hand-written refused row, one test each.
  rows.forEach((row, index) => {
    if (row.source !== "edge") return;
    if (row.data === null) {
      lines.push(
        `test expect_deserialise_fails_on_row_${pad3(index)}() fail {`,
      );
      lines.push(
        `  cbor_deserialise.expect_deserialise(${aikenBytes(row.input)}, fn(_) { True })`,
      );
      lines.push("}");
      lines.push("");
    }
    if (row.envelope === null) {
      lines.push(
        `test expect_deserialise_envelope_fails_on_row_${pad3(index)}() fail {`,
      );
      lines.push(
        `  cbor_deserialise.expect_deserialise_envelope(${aikenBytes(row.input)}, fn(_) { True })`,
      );
      lines.push("}");
      lines.push("");
    }
  });

  // The failing variants on the mutated rows, sampled.
  const mutated = (outcome) =>
    rows
      .filter((row) => row.source === "mutated" && row[outcome] === null)
      .map((row) => `    ${aikenBytes(row.input)},`);
  lines.push("fn refused_mutated_rows() -> List<ByteArray> {");
  lines.push("  [");
  lines.push(...mutated("data"));
  lines.push("  ]");
  lines.push("}");
  lines.push("");
  if (mutated("envelope").join("\n") !== mutated("data").join("\n")) {
    throw new Error(
      "a mutated row is refused by one entry only; give each entry its own list",
    );
  }
  lines.push(
    "test expect_deserialise_fails_on_mutated_rows(",
    "  input via fuzz.one_of(refused_mutated_rows()),",
    ") fail {",
    "  cbor_deserialise.expect_deserialise(input, fn(_) { True })",
    "}",
    "",
    "test expect_deserialise_envelope_fails_on_mutated_rows(",
    "  input via fuzz.one_of(refused_mutated_rows()),",
    ") fail {",
    "  cbor_deserialise.expect_deserialise_envelope(input, fn(_) { True })",
    "}",
  );
  return `${lines.join("\n")}\n`;
};

writeOrCheck(generatedJsonPath, `${JSON.stringify({ rows }, null, 2)}\n`);
writeOrCheck(
  generatedAikenPath,
  formatAikenSource({
    source: renderAiken(),
    fileName: "cbor-deserialise-v1-golden.test.ak",
    repositoryRoot,
    tmpPrefix: "midgard-plutus-data-cbor-decoding-aiken-format-",
  }),
);
