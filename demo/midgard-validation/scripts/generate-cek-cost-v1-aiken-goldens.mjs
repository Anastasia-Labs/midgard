#!/usr/bin/env node

/**
 * Produces `onchain/aiken/lib/midgard/cek-cost-v1-golden.test.ak`: for every
 * Plutus V3 builtin tag (0 to 86), the cpu and memory that
 * `cek_cost_v1.builtin_budget_v1` must charge at a spread of argument sizes.
 *
 * The expected budgets come from `computeMidgardCekBuiltinBudget`, which reads
 * every cost parameter from midgard-core's pinned 350-entry Plutus V3 cost
 * vector (`PLUTUS_V3_CANONICAL_COST_MODEL_VIEW`). The size points are chosen so
 * that every parameter of every cost model moves the result: an intercept and
 * a slope, both sides of a diagonal, equal and unequal sizes, a zero literal
 * and a non-zero one. Changing any single on-chain cost parameter therefore
 * fails at least one generated row.
 *
 * usage: node scripts/generate-cek-cost-v1-aiken-goldens.mjs [--check]
 * (run `pnpm run build` first; it reads `dist`).
 */

import { basename, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import {
  PLUTUS_V3_CANONICAL_COST_MODEL_VIEW,
  PLUTUS_V3_CANONICAL_COST_MODEL_VIEW_LENGTH,
} from "@al-ft/midgard-core";
import {
  formatAikenSource,
  goldenChannelEmitter,
  parseGoldenChannelArguments,
} from "@al-ft/midgard-core/scripts/golden-channel.mjs";
import { PartialBuiltin } from "@harmoniclabs/plutus-machine";
import { builtinTagToString } from "@harmoniclabs/uplc";

import {
  computeMidgardCekBuiltinBudget,
  harmonicBuiltinTag,
} from "../dist/index.js";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(scriptDirectory, "..");
const repositoryRoot = resolve(packageRoot, "../..");
const generatedAikenPath = resolve(
  repositoryRoot,
  "onchain/aiken/lib/midgard/cek-cost-v1-golden.test.ak",
);
const aikenFileName = basename(generatedAikenPath);

const { checkOnly } = parseGoldenChannelArguments(
  "usage: node scripts/generate-cek-cost-v1-aiken-goldens.mjs [--check]",
);
const writeOrCheck = goldenChannelEmitter({ repositoryRoot, checkOnly });

if (
  PLUTUS_V3_CANONICAL_COST_MODEL_VIEW.length !== 350 ||
  PLUTUS_V3_CANONICAL_COST_MODEL_VIEW_LENGTH !== 350
) {
  throw new Error("the pinned Plutus V3 cost vector must have 350 entries");
}

const MAX_BUILTIN_TAG = 86;

/** Argument-size points per arity. */
const SIZE_POINTS = new Map([
  [1, [[0], [1], [7], [100]]],
  [
    2,
    [
      [0, 3],
      [3, 0],
      [1, 1],
      [2, 10],
      [10, 2],
      [7, 7],
      [100, 37],
    ],
  ],
  [
    3,
    [
      [1, 1, 1],
      [1, 2, 3],
      [3, 2, 1],
      [2, 3, 1],
      [5, 0, 9],
      [5, 9, 0],
      [0, 4, 4],
      [100, 37, 64],
    ],
  ],
  [
    6,
    [
      [1, 1, 1, 1, 1, 1],
      [1, 2, 3, 4, 5, 6],
    ],
  ],
]);

const snakeCase = (name) =>
  name
    .replace(/([a-z0-9])([A-Z])/gu, "$1_$2")
    .replace(/[^A-Za-z0-9]+/gu, "_")
    .toLowerCase();

const renderTest = (tag) => {
  const harmonicTag = harmonicBuiltinTag(tag);
  const name = builtinTagToString(harmonicTag);
  const arity = PartialBuiltin.getNRequiredArgsFor(harmonicTag);
  const points = SIZE_POINTS.get(arity);
  if (points === undefined) {
    throw new Error(`no size points for arity ${String(arity)} (tag ${tag})`);
  }
  const rows = points.map((sizes) => {
    const { cpu, memory } = computeMidgardCekBuiltinBudget(
      tag,
      sizes.map(BigInt),
    );
    return `    cek_cost_v1.builtin_budget_v1(${tag}, [${sizes.join(", ")}]) == cek_cost_v1.BuiltinBudgetV1 { cpu: ${cpu}, memory: ${memory} },`;
  });
  return `
// ${name}
test budget_${String(tag).padStart(2, "0")}_${snakeCase(name)}() {
  and {
${rows.join("\n")}
  }
}
`;
};

const tags = Array.from({ length: MAX_BUILTIN_TAG + 1 }, (_, tag) => tag);
const source = `//// GENERATED by demo/midgard-validation/scripts/generate-cek-cost-v1-aiken-goldens.mjs
//// from the pinned 350-entry Plutus V3 cost vector.
//// Do not edit; run \`pnpm --dir demo/midgard-validation run fixtures:cek-cost-v1-aiken:sync\`.

use midgard/cek_cost_v1
${tags.map(renderTest).join("")}`;

writeOrCheck(
  generatedAikenPath,
  formatAikenSource({
    source,
    fileName: aikenFileName,
    repositoryRoot,
    tmpPrefix: "cek-cost-v1-aiken-",
  }),
);
